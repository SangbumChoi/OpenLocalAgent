def rewrite(text: str, key: str, value: str) -> str:
    """Replace a scalar YAML value in place, keeping indentation and any trailing comment."""
    pattern = re.compile(rf"^(\s*{re.escape(key)}:\s*)(\S+)(.*)$", re.M)
    if not pattern.search(text):
        raise KeyError(f"key {key!r} not found; refusing to add it silently")
    return pattern.sub(lambda m: f"{m.group(1)}{value}{m.group(3)}", text, count=1)


def retarget(text: str, base: str, tier: str) -> str:
    """Point out_dir and init_from at this tier's own runs, never the base tier's.

    Getting this wrong is silent and expensive: the arm would train, write over the base tier's
    checkpoint, and produce a receipt attributed to the wrong run.
    """
    return text.replace(f"la-{base}/", f"la-{tier}/").replace(f"la-{base}\n", f"la-{tier}\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tiers", nargs="*", help="variant names, or none with --list")
    parser.add_argument("--list", action="store_true", help="show the declared arms")
    parser.add_argument("--check", action="store_true", help="diff generated arms against base")
    args = parser.parse_args()

    if args.list:
        for name, v in VARIANTS.items():
            print(f"{name:<14} base=la-{v.base}")
            print(f"  {v.why}")
            for stage, over in v.overrides.items():
                print(f"    {stage}: " + ", ".join(f"{k}={val}" for k, val in over.items()))
        return 0

    tiers = args.tiers or list(VARIANTS)
    for name in tiers:
        if name not in VARIANTS:
            print(f"unknown arm {name!r}; known: {sorted(VARIANTS)}", file=sys.stderr)
            return 1
        variant = VARIANTS[name]
        if args.check:
            problems = variant.check()
            print(f"{name}: {'OK - differs only where declared' if not problems else 'PROBLEM'}")
            for p in problems:
                print("  " + p)
            if problems:
                return 1
        else:
            for path in variant.generate():
                print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
