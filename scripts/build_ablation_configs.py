#!/usr/bin/env python
"""Derive a tier's three stage configs from a base tier, changing one thing on purpose.

An ablation is only an ablation if everything except the variable is byte-identical. Hand-copying
four YAMLs and editing three fields is how a stray difference gets into a comparison and is never
noticed - the corpus-scale arms differ by one line each, and that line has to be the only one.

So the base files stay the source of truth: this rewrites exactly the keys named in a VARIANT and
rechains init_from/out_dir onto the new tier name, then writes a provenance header saying what was
changed and from what. Anything not listed is inherited, and `--check` proves it by diffing the
generated file against its base.

  python scripts/build_ablation_configs.py --list
  python scripts/build_ablation_configs.py 93m-s2 93m-s3
  python scripts/build_ablation_configs.py --check 93m-s2
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from openlocalagent.stages import Stage  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
#: The spine, in order. Taken from the project's own vocabulary rather than restated as strings,
#: so a stage rename cannot leave this script silently generating configs for a stage that moved.
STAGES: tuple[Stage, ...] = (Stage.PRETRAIN, Stage.MIDTRAIN, Stage.POSTTRAIN)


@dataclass(frozen=True)
class Variant:
    """One arm: the base tier it copies, and the keys it is allowed to differ in."""

    tier: str
    base: str
    why: str
    #: stage -> {yaml key: new value}. A key absent here is inherited verbatim.
    overrides: dict[str, dict[str, str]] = field(default_factory=dict)

    def stage_overrides(self, stage: Stage) -> dict[str, str]:
        return self.overrides.get(str(stage), {})

    def config_path(self, stage: Stage, tier: str) -> Path:
        return ROOT / "configs" / str(stage) / f"la-{tier}.yaml"

    def generate(self) -> list[Path]:
        """Write this arm's three stage configs from its base."""
        written = []
        for stage in STAGES:
            text = self.config_path(stage, self.base).read_text(encoding="utf-8")
            for key, value in self.stage_overrides(stage).items():
                text = rewrite(text, key, value)
            text = retarget(text, self.base, self.tier)
            changed = self.stage_overrides(stage) or {"(nothing)": "inherited verbatim"}
            header = (
                f"# GENERATED by scripts/build_ablation_configs.py from configs/{stage}/"
                f"la-{self.base}.yaml\n"
                f"# Arm: {self.tier}. {self.why}\n"
                f"# Changed in this stage: "
                + ", ".join(f"{k}={v}" for k, v in changed.items())
                + "\n# Everything else is inherited on purpose - edit the base tier, not this.\n"
            )
            out = self.config_path(stage, self.tier)
            out.write_text(header + text, encoding="utf-8")
            written.append(out)
        return written

    def check(self) -> list[str]:
        """Every line differing from the base that this arm did not declare."""
        problems = []
        for stage in STAGES:
            base = self.config_path(stage, self.base).read_text().splitlines()
            made = [line for line in self.config_path(stage, self.tier).read_text().splitlines()
                    if not line.startswith(("# GENERATED", "# Arm:", "# Changed in",
                                            "# Everything else"))]
            allowed = set(self.stage_overrides(stage))
            for a, b in zip(base, made):
                if a == b or b.split(":")[0].strip() in allowed or f"la-{self.tier}" in b:
                    continue
                problems.append(f"{stage}: undeclared change\n    base: {a}\n    arm : {b}")
        return problems


